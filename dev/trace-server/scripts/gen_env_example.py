#!/usr/bin/env python3
"""Regenerate .env.example from the Settings model.

The model in app/config.py is the single source of truth for configuration. This
script projects it into the template so the two can never drift:

    python scripts/gen_env_example.py

Every field becomes one KEY=value entry under a section header taken from the
`# comment` groups in config.py. Those headers are the only comments: key names are
self-explanatory, and a `changeme` value marks a key that must be filled in. Secret
fields (typed SecretStr) never carry a real value here, because this file is committed.

Run this after adding, removing or renaming any field, then commit the result.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

SERVER_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SERVER_DIR))

from pydantic import SecretStr, ValidationError  # noqa: E402

# A value no validator will accept as real, used only to get the class to import when
# .env does not exist yet. It never reaches the generated template, which is built from
# the field definitions rather than from any instance.
BOOTSTRAP = "__template_bootstrap__"


def load_settings_class():
    """Return the Settings class, even with no .env present.

    app/config.py ends with `settings = Settings()`, so a plain import fails when .env
    is absent or incomplete — which is exactly when you need this script to bootstrap a
    template. pydantic names the missing fields, so they are filled with a throwaway
    value in os.environ and the import retried.
    """
    try:
        from app.config import Settings  # noqa: PLC0415

        return Settings
    except ValidationError as exc:
        missing = [
            str(err["loc"][0]).upper()
            for err in exc.errors(include_url=False)
            if err["type"] == "missing" and err["loc"]
        ]
        if not missing:
            raise
        for key in missing:
            os.environ.setdefault(key, BOOTSTRAP)
        sys.modules.pop("app.config", None)
        try:
            from app.config import Settings  # noqa: PLC0415
        except ValidationError as exc2:
            raise SystemExit(
                "cannot load the settings model even with placeholder values:\n  "
                + "\n  ".join(
                    f"{'.'.join(str(p) for p in e['loc'])}: {e['msg']}"
                    for e in exc2.errors(include_url=False)
                )
            ) from None
        print(f"note: .env missing or incomplete ({len(missing)} keys) — "
              "generating from the model definition")
        return Settings


Settings = load_settings_class()

PLACEHOLDER = "changeme"
HEADER = """\
# .env.example — generated by scripts/gen_env_example.py. Do not edit by hand.
#
# Copy to .env and fill in the real values:   cp .env.example .env
# Any key showing `changeme` has no default and must be set — the server refuses to
# start otherwise. Every other value below is the development default.
# .env is git-ignored. This file is committed, so it must never hold a real secret.
"""


ACRONYMS = {"api", "db", "jwt", "smtp", "url"}


def field_sections() -> dict[str, str]:
    """Map field name -> section title, read from the `# comment` groups in config.py.

    The model already groups its fields under comment headers, so those are the single
    source for the section names too — nothing to keep in sync here. A comment line
    inside the class body opens a section; every field after it belongs to that section
    until the next comment.
    """
    source = (SERVER_DIR / "app" / "config.py").read_text(encoding="utf-8")
    sections: dict[str, str] = {}
    current = ""
    in_class = False
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith("class Settings"):
            in_class = True
            continue
        if not in_class:
            continue
        if stripped.startswith(("@", "def ")):  # validators end the field block
            break
        if stripped.startswith("#"):
            title = stripped.lstrip("#").strip()
            title = title.split(" — ")[0].split(" - ")[0].strip()  # drop trailing prose
            if title:
                words = [w.upper() if w.lower() in ACRONYMS else w for w in title.split()]
                current = " ".join(words)
                current = current[0].upper() + current[1:]
            continue
        match = re.match(r"^\s{4}([a-z_][a-z0-9_]*)\s*:", line)
        if match and current:
            sections[match.group(1)] = current
    return sections


def main() -> int:
    sections = field_sections()
    out = [HEADER]
    current_section = None
    for name, field in Settings.model_fields.items():
        section = sections.get(name, "Other")
        if section != current_section:
            rule = "# " + "-" * 74
            if current_section is not None:
                out.append("")
            out.extend([rule, f"# {section}", rule, ""])
            current_section = section
        # Section headers are the only comments: the key names say what they are, and a
        # `changeme` value says it must be filled in. Descriptions live in config.py.
        secret = field.annotation is SecretStr
        value = PLACEHOLDER if (field.is_required() or secret) else field.default
        out.append(f"{name.upper()}={value}")

    target = SERVER_DIR / ".env.example"
    # trailing newline: without it git reports "\ No newline at end of file" on every diff
    target.write_text("\n".join(out) + "\n", encoding="utf-8")

    required = sum(1 for f in Settings.model_fields.values() if f.is_required())
    print(f"wrote {target}")
    print(f"  {len(Settings.model_fields)} keys, {required} required")
    return 0


if __name__ == "__main__":
    sys.exit(main())
